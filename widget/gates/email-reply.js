/* What arrived in the mailbox, and whether a person sent it.

   The Channels report has counted emails sent and texts replied to since it
   was built, so "replied" has meant "replied by text" and every per-channel
   reply rate has been wrong in the same direction. Reading the mailbox
   fixes that and introduces a worse way to be wrong.

   **An auto-reply is not a reply.** Out-of-office, bounces, "thanks, we
   have your enquiry", newsletters: each arrives as inbound mail, and each
   would mark somebody as having replied, stop their follow-up, and inflate
   the figure the client reads. Counting those is worse than the gap it
   replaces, because a known gap can be explained and a wrong number gets
   repeated in a meeting.

   So most of this file is refusals, and the matching is the easy half.

   Plain JavaScript, no imports, like everything in gates/. */

/* Headers arrive with whatever capitalisation the sending server felt like.
   RFC 5322 says they are case-insensitive, so they are lowercased once here
   rather than guessed at per lookup. */
function headersOf(msg) {
  var out = {};
  var h = (msg && msg.headers) || {};
  for (var k in h) {
    if (Object.prototype.hasOwnProperty.call(h, k)) {
      out[String(k).toLowerCase()] = String(h[k] == null ? "" : h[k]);
    }
  }
  return out;
}

/* A local part that nobody reads replies to. */
var ROBOT_LOCALS = ["mailer-daemon", "postmaster", "no-reply", "noreply", "donotreply", "do-not-reply"];

/* Only at the START of a subject. A person can write "Re: booking while I
   am out of office", and refusing that loses a real reply, which is the
   expensive mistake in both directions. */
var AUTO_SUBJECT = /^\s*(?:re\s*:\s*)?(out of (?:the )?office|automatic reply|auto(?:matic)?[- ]?response|undeliverable|delivery status notification|mail delivery (?:failed|subsystem)|returned mail|absence|autoreply)\b/i;

/** Was this generated by a machine rather than written by somebody? */
function isAutoReply(msg) {
  if (!msg || typeof msg !== "object") return true;
  var h = headersOf(msg);

  /* RFC 3834 exists exactly to answer this, so it is asked first. "no" is
     a legitimate value meaning a person sent it. */
  var auto = (h["auto-submitted"] || "").toLowerCase();
  if (auto && auto.indexOf("no") !== 0) return true;

  if (h["x-autoreply"] || h["x-autorespond"] || h["x-auto-response-suppress"]) return true;

  var prec = (h["precedence"] || "").toLowerCase();
  if (prec === "bulk" || prec === "junk" || prec === "auto_reply" || prec === "list") return true;

  /* A mailing list is not somebody answering us. */
  if (h["list-id"] || h["list-unsubscribe"]) return true;

  /* The standard marker of a bounce: nowhere to send a bounce of a bounce. */
  var rp = (h["return-path"] || "").replace(/\s/g, "");
  if (rp === "<>" || rp === "") {
    if (rp === "<>") return true;
  }

  var ct = String(msg.contentType || h["content-type"] || "").toLowerCase();
  if (ct.indexOf("report-type=delivery-status") !== -1 || ct.indexOf("multipart/report") !== -1) {
    return true;
  }

  var from = String(msg.from || h["from"] || "").toLowerCase();
  for (var i = 0; i < ROBOT_LOCALS.length; i++) {
    /* Matched against the local part, so "no-reply@x" is caught and
       "jane@no-reply-studios.com" is not. */
    if (from.indexOf(ROBOT_LOCALS[i] + "@") !== -1) return true;
  }

  /* Last, and only the start of the line. */
  if (AUTO_SUBJECT.test(String(msg.subject || ""))) return true;

  return false;
}

/* `replies+t<id>@domain` on any recipient header. */
function tokenIn(value) {
  var m = /\+t([A-Za-z0-9_-]{1,64})@/.exec(String(value || ""));
  return m ? m[1] : null;
}

/* The ids a reply points back at, newest first.

   `References` is oldest to newest, so it is walked backwards: the newest
   is the message actually being answered, and an old one would attribute
   the reply to the wrong step of the sequence. */
function threadIds(msg) {
  var h = headersOf(msg);
  var ids = [];
  var inReplyTo = (h["in-reply-to"] || "").match(/<[^>]+>/g) || [];
  for (var i = 0; i < inReplyTo.length; i++) ids.push(inReplyTo[i]);
  var refs = (h["references"] || "").match(/<[^>]+>/g) || [];
  for (var j = refs.length - 1; j >= 0; j--) ids.push(refs[j]);
  return ids;
}

/**
 * Which outbound touch this is answering.
 *
 * @param msg    the parsed inbound message
 * @param lookup (messageId) => touchId | null, asked of the database
 *
 * Threading first because it works on any mailbox with no configuration.
 * The plus token second because it survives a client that does not thread.
 * Their weaknesses do not overlap, which is the only reason to carry both.
 */
function touchIdFrom(msg, lookup) {
  if (!msg || typeof msg !== "object") return null;
  var ids = threadIds(msg);
  for (var i = 0; i < ids.length; i++) {
    var hit = lookup ? lookup(ids[i]) : null;
    if (hit) return hit;
  }
  return null;
}

/** The `+t<token>` on any recipient header, where the token identifies the
    send rather than the touch: the touch does not exist yet when the
    address is written. */
function tokenFrom(msg) {
  if (!msg || typeof msg !== "object") return null;
  var h = headersOf(msg);
  var candidates = [msg.to, h["to"], h["delivered-to"], h["x-original-to"], h["envelope-to"], h["cc"]];
  for (var c = 0; c < candidates.length; c++) {
    var t = tokenIn(candidates[c]);
    if (t) return t;
  }
  return null;
}

/**
 * The whole answer: what it is about, and whether it counts.
 *
 * An auto-reply still gets identified. Knowing which message bounced is
 * worth having even though it is not a reply.
 */
function readReply(msg, lookup) {
  if (!msg || typeof msg !== "object") {
    return { reply: false, touchId: null, token: null, why: "no_message" };
  }
  /* Two identifiers, resolved by different lookups and therefore kept
     apart. `touchId` is one of ours, found by threading. `token` is what
     we wrote into the Reply-To, which names the SEND rather than the
     touch, because the touch does not exist yet at that moment. */
  var touchId = touchIdFrom(msg, lookup);
  var token = touchId ? null : tokenFrom(msg);

  if (isAutoReply(msg)) {
    return { reply: false, touchId: touchId, token: token, why: "auto_reply" };
  }
  if (!touchId && !token) {
    return { reply: false, touchId: null, token: null, why: "unmatched" };
  }
  return { reply: true, touchId: touchId, token: token, why: "" };
}

/**
 * Does this inbound touch mean the person answered?
 *
 * Asked in two places that must agree: when a message arrives, and later
 * by the sequence worker, which stops a follow-up the moment anything
 * inbound has arrived since enrolment. An out-of-office is recorded on the
 * timeline so the team can see one came back, and if the worker counted it
 * the follow-up would stop anyway, by the back door, and the reply rate
 * would include it. One rule, read by both.
 */
function countsAsReply(touch) {
  if (!touch || typeof touch !== "object") return false;
  if (touch.direction !== "in") return false;
  return touch.status !== "auto_reply";
}

export { isAutoReply, touchIdFrom, tokenFrom, readReply, countsAsReply, threadIds, tokenIn };
